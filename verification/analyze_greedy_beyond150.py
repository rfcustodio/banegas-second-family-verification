#!/usr/bin/env python3
"""Section VIII, paragraph after Figure 2: the regularities of Observation 18 beyond
m = 150. Reads the output of `greedy fam2` (lexicographic ties) for all members with
151 <= m <= 300 and for the degrees 500, 800 and 1100 (default: data/greedy_beyond150.txt,
regenerated by greedy_beyond150.sh) and compares with the numbers printed in the paper.
Standard library only.  Usage: python3 analyze_greedy_beyond150.py [FILE]"""
import os, sys
from math import gcd
here = os.path.dirname(os.path.abspath(__file__))
fn = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'data', 'greedy_beyond150.txt')
BASE = {(2, 1), (3, 1), (4, 1), (5, 1), (3, 2)}                       # Definition 3
R = [list(map(int, l.split())) for l in open(fn) if l[:1].isdigit()]
ok = True
def expect(label, got, want):
    global ok
    good = got == want; ok &= good
    print(f"  {'ok ' if good else 'BAD'} {label}: {got}" + ('' if good else f'  (paper: {want})'))
for name, sel, want in (('151 <= m <= 300', lambda m: 151 <= m <= 300, (11175, 598, 4163, 248)),
                        ('m in {500, 800, 1100}', lambda m: m in (500, 800, 1100), (798, 36, 299, 994))):
    S = [r for r in R if sel(r[0])]
    G = [r for r in S if (r[1] // gcd(r[1], r[2]), r[2] // gcd(r[1], r[2])) not in BASE]
    closed = lambda r: 3 * r[0] - r[2] - 3
    A = [r for r in G if r[1] < 2 * r[2]]; B = [r for r in G if 2 * r[2] < r[1] < 6 * r[2]]
    C = [r for r in G if r[1] >= 6 * r[2]]
    print(name)
    expect('members', len(S), want[0])
    expect('closed form never more expensive than the greedy count (generic)', all(closed(r) <= r[4] for r in G), True)
    expect('b < 2c: greedy count = 2m+3c-3 for all', all(r[4] == 2 * r[0] + 3 * r[2] - 3 for r in A), True)
    expect('2c < b < 6c: greedy count = 3m-c-3 for all', all(r[4] == closed(r) for r in B), True)
    expect('b >= 6c: (greedy worse, members, largest excess)',
           (sum(r[4] > closed(r) for r in C), len(C), max(r[4] - closed(r) for r in C)), want[1:])
print('\nALL OK' if ok else '\nSOME VALUES DIFFER')
sys.exit(0 if ok else 1)
